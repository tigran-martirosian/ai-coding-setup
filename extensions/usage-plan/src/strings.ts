/** Russian plural form for a count: 1 / 2-4 / the rest. */
const ruPlural = (n: number, one: string, few: string, many: string) => {
  const m10 = n % 10;
  const m100 = n % 100;
  return m10 === 1 && m100 !== 11
    ? one
    : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)
      ? few
      : many;
};

